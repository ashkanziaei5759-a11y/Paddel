/**
 * اطلاعات بانکی بازیکن — اعتبارسنجی، تشخیص بانک، و پوشاندن رقم‌ها.
 *
 * این ماژول عمداً هیچ چیزی از دیتابیس نمی‌خواند: فقط رشته‌ها را می‌سنجد.
 * تصمیمِ «چه کسی حق دیدن دارد» جای دیگری گرفته می‌شود (RBAC)، ولی «چه چیزی
 * نشان داده شود» اینجاست، تا هیچ صفحه‌ای به‌اشتباه شماره‌ی کامل چاپ نکند.
 *
 * عمداً server-only نیست: فرم ورودی هم باید همین‌جا اعتبارسنجی کند تا کاربر
 * پیش از ارسال بفهمد رقمی را اشتباه زده. اعتبارسنجیِ سمت سرور جدا و مستقل
 * دوباره انجام می‌شود — این یکی فقط برای راحتی کاربر است.
 */

/** فقط ارقام لاتین را نگه می‌دارد و ارقام فارسی/عربی را به لاتین برمی‌گرداند */
export function normalizeDigits(input: string): string {
  return input
    .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
    .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/\D/g, '');
}

