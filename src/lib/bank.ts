/**
 * شبای ایران: IR + ۲۴ رقم. اعتبارسنجی استاندارد IBAN است (ISO 13616):
 * چهار نویسه‌ی اول به آخر منتقل می‌شود، حروف به عدد تبدیل می‌شوند
 * (I=18، R=27) و باقی‌مانده‌ی کل عدد بر ۹۷ باید ۱ باشد.
 *
 * عدد ۲۶ نویسه‌ای از محدوده‌ی Number جاوااسکریپت بیرون می‌زند، پس
 * باقی‌مانده را تکه‌تکه حساب می‌کنیم.
 */
export function isValidIban(raw: string): boolean {
  const s = raw.replace(/\s/g, '').toUpperCase().replace(/^IR/, '');
  const digits = normalizeDigits(s);
  if (digits.length !== 24) return false;
  if (/^0+$/.test(digits)) return false;

  /* digits = دو رقمِ کنترلی + ۲۲ رقم شناسه. طبق استاندارد، چهار نویسه‌ی
     نخستِ شبا (یعنی IR + دو رقم کنترلی) به انتها منتقل می‌شود؛ چون «IR» را
     بالاتر جدا کرده‌ایم، معادلش می‌شود: ۲۲ رقم + «1827» + دو رقم کنترلی. */
  const rearranged = `${digits.slice(2)}1827${digits.slice(0, 2)}`;
  let remainder = 0;
  for (const ch of rearranged) {
    remainder = (remainder * 10 + Number(ch)) % 97;
  }
  return remainder === 1;
}

/** همیشه با پیشوند IR و بدون فاصله ذخیره و مقایسه می‌شود */
export function normalizeIban(raw: string): string {
  return normalizeDigits(raw.replace(/^IR/i, ''));
}

/** IR۰۶۰۱۲**********۳۴۵۶ */
export function maskIban(iban: string): string {
  const d = normalizeIban(iban);
  if (d.length !== 24) return '****';
  return `IR${d.slice(0, 5)}**********${d.slice(20)}`;
}

/** IR06 0120 0000 0000 0000 1234 — خواناتر برای کپی‌کردن */
export function formatIban(iban: string): string {
  const d = normalizeIban(iban);
  return `IR${d}`.replace(/(.{4})(?=.)/g, '$1 ').trim();
}
