/**
 * الگوریتم لون (Luhn) روی ۱۶ رقم. شبکه‌ی شتاب همین را به‌کار می‌برد، پس
 * یک اشتباه تایپی معمولی (یک رقم غلط یا جابه‌جایی دو رقم) همین‌جا گرفته
 * می‌شود و پول به حساب اشتباه نمی‌رود.
 */
export function isValidCardNumber(raw: string): boolean {
  const d = normalizeDigits(raw);
  if (d.length !== 16) return false;
  if (/^(\d)\1{15}$/.test(d)) return false; // ۱۶ رقم یکسان، قطعاً جعلی

  let sum = 0;
  for (let i = 0; i < 16; i++) {
    let n = Number(d[i]);
    if (i % 2 === 0) {
      n *= 2;
      if (n > 9) n -= 9;
    }
    sum += n;
  }
  return sum % 10 === 0;
}

