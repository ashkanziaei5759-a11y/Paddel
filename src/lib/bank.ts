export function detectBank(cardNumber: string): string | null {
  const d = normalizeDigits(cardNumber);
  if (d.length < 6) return null;
  return BANK_BINS[d.slice(0, 6)] ?? null;
}

/**
 * ۶۰۳۷۹۹******۱۲۳۴ — شش رقم اول (بانک) و چهار رقم آخر (برای اینکه بازیکن
 * کارت خودش را بشناسد) می‌ماند؛ شش رقم میانی پوشیده می‌شود.
 */
export function maskCardNumber(cardNumber: string): string {
  const d = normalizeDigits(cardNumber);
  if (d.length !== 16) return '****';
  return `${d.slice(0, 6)}******${d.slice(12)}`;
}

/** ۶۰۳۷-۹۹۱۱-۲۲۳۳-۴۴۵۵ — فقط برای جایی که نمایش کامل مجاز است */
export function formatCardNumber(cardNumber: string): string {
  const d = normalizeDigits(cardNumber);
  return d.replace(/(\d{4})(?=\d)/g, '$1-');
}

