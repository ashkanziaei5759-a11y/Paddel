#!/bin/sh
# اعمال مهاجرت‌های پایگاه داده پیش از بالا آمدن اپلیکیشن.
# اجرای دوباره بی‌خطر است — مهاجرت‌های اعمال‌شده دوباره اجرا نمی‌شوند.
set -e

if [ "${RUN_MIGRATIONS:-true}" = "true" ]; then
  echo "→ در حال اعمال مهاجرت‌های پایگاه داده…"
  ./node_modules/.bin/prisma migrate deploy || {
    echo "✗ اعمال مهاجرت‌ها ناموفق بود. DATABASE_URL را بررسی کنید."
    exit 1
  }
  echo "✓ پایگاه داده به‌روز است."
fi

exec "$@"
