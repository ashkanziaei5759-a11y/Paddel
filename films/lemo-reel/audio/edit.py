# Voice edit: cut the cleaned recording into phrases, place them on the 40 s film timeline,
# and derive every visual anchor and subtitle cue from the same word times (one timeline drives everything).
#   python audio/edit.py   → audio/voice_edit.wav, timing.json, out/cues.json
import json, os, numpy as np, soundfile as sf

HERE = os.path.dirname(os.path.abspath(__file__)); FILM = os.path.dirname(HERE)
SR = 48000; END = 40.0; FADE = .012

# (raw in, raw out, film start). Cut points sit in measured silences (−45…−55 dB); the list pauses in
# section 2 are tightened to ~0.1 s so it fits its 6–17 s window, and the steps in section 3 get air.
PIECES = [
    (1.20, 5.80, 0.90),                                  # hook
    (6.00, 10.84, 6.25), (11.06, 12.00, None), (12.22, 13.13, None), (13.32, 14.40, None), (14.60, 15.46, None), (15.62, 17.70, None),
    (18.40, 19.62, 17.60),                               # how it works?
    (19.85, 23.20, 19.80),                               # step 1
    (23.40, 25.80, 24.00),                               # step 2
    (26.10, 28.40, 27.60),                               # step 3
    (28.85, 31.40, 32.50),                               # this film was made the same way
    (32.05, 35.47, 35.40),                               # comment «ریپو» (the click at 35.96 s is left out)
]
pl = []; cur = None
for a, b, f in PIECES:
    f = cur if f is None else f; pl.append((a, b, f)); cur = f + (b - a)

def M(r):                                                # raw time → film time
    for a, b, f in pl:
        if a - .02 <= r <= b + .02: return round(f + (r - a), 3)
    best = min(pl, key=lambda p: min(abs(r - p[0]), abs(r - p[1])))
    return round(best[2] + (r - best[0]), 3)

x, sr = sf.read(os.path.join(HERE, 'voice_clean.wav')); assert sr == SR
if x.ndim > 1: x = x.mean(1)
out = np.zeros(int(END * SR))
for a, b, f in pl:
    seg = x[int(a * SR):int(b * SR)].copy(); n = int(FADE * SR)
    seg[:n] *= np.linspace(0, 1, n); seg[-n:] *= np.linspace(1, 0, n)
    i = int(f * SR); out[i:i + len(seg)] += seg
sf.write(os.path.join(HERE, 'voice_edit.wav'), out, SR, subtype='PCM_24')

# word times in the raw recording (from the alignment of the Persian script to the recognizer's syllable chunks)
W = dict(dorbin=(2.45, 2.85), editor=(3.15, 3.66), footage=(5.25, 5.73),
         matnbaz=(6.48, 7.08), lemo=(7.50, 8.52), n39=(9.00, 9.57), sabk=(9.68, 10.74),
         abrang=(11.34, 11.97), icon=(12.22, 13.11), silent=(13.32, 14.34), pixel=(14.64, 15.42), wb=(15.66, 16.32), more=(16.35, 17.67),
         how=(18.48, 19.53), link=(19.95, 21.13), copy=(21.13, 21.69), claude=(21.75, 22.38), paste=(22.38, 23.10),
         sabk2=(23.49, 24.51), story=(24.51, 25.68), claude2=(26.22, 27.39), work=(27.39, 28.20),
         thisfilm=(28.95, 31.23), baraye=(32.19, 33.18), repo=(34.40, 34.75), comment=(34.86, 35.25))
F = {k: (M(a), M(b)) for k, (a, b) in W.items()}
r = lambda v: round(v, 3)
A = {
    'hook': [[r(F['dorbin'][1] - .95), F['dorbin'][1], r(F['dorbin'][1] + .05), r(F['dorbin'][1] + .27)],
             [r(F['editor'][1] - .58), F['editor'][1], r(F['editor'][1] + .05), r(F['editor'][1] + .26)],
             [r(F['footage'][1] - .95), F['footage'][1], r(F['footage'][1] + .03), r(F['footage'][1] + .25)]],
    'zero': [r(F['footage'][1] + .3), r(F['footage'][1] + .82)],
    'open': [r(F['matnbaz'][0] - .05), r(F['matnbaz'][1] + .2)],
    'title': [r(F['lemo'][0]), r(F['lemo'][1] + .05)],
    'n39': [r(F['n39'][0] + .05), r(F['n39'][1])],
    'styles': [r(F[k][0] + .12) for k in ('abrang', 'icon', 'silent', 'pixel')] + [r(F['wb'][0] + .3)],
    'burst': [r(F['more'][0] + .05), r(F['more'][1] - .2)],
    'how': [r(F['how'][0] - .03), r(F['how'][1] + .02)],
    'step1': [r(F['link'][0] - .35), r(F['link'][1]), r(F['claude'][0] - .1), r(F['paste'][0] + .22), r(F['paste'][1])],
    'step2': [r(F['sabk2'][0] - .45), r(F['sabk2'][0] + .55), r(F['sabk2'][0] + .7), r(F['story'][0] + .1), r(F['story'][1] + .05)],
    'step3': [r(F['claude2'][0] - .4), r(F['work'][0] - .2), r(F['work'][1] + .05), r(F['work'][1] + .45), r(F['work'][1] + .85)],
    'end': {'pull0': 32.5, 'rw0': 33.2, 'rw1': 33.75, 'ff1': r(F['thisfilm'][1] + .1), 'push0': r(F['thisfilm'][1] + .1), 'push1': r(F['thisfilm'][1] + .75),
            'box0': r(F['baraye'][0] - .05), 'cc0': r(F['baraye'][1] - .2), 'cc1': r(F['baraye'][1] + .75),
            'word0': r(F['repo'][0] - .15), 'word1': r(F['repo'][1] + .05), 'cap': 39.2},
}
json.dump({'note': 'generated by audio/edit.py', 'anchors': A, 'words': F, 'pieces': pl}, open(os.path.join(FILM, 'timing.json'), 'w'), ensure_ascii=False, indent=1)

# subtitles (Persian, burned in and exported as .srt): clause spans in raw time
SUBS = [
    (1.17, 3.66, 'فیلم ساختم، بدون دوربین، بدون ادیتور،'),
    (3.66, 5.73, 'بدون حتی یک ثانیه فوتیج.'),
    (6.03, 8.52, 'یه ریپوی متن‌باز هست به اسم Lemo-Opuscar'),
    (9.00, 10.74, 'که ۳۹ سبک فیلم‌سازی داره:'),
    (11.10, 14.34, 'آبرنگ، آیکون‌نگاری، سینمای صامت،'),
    (14.64, 17.67, 'پیکسل‌آرت، سبک وایت‌بورد و کلی چیز دیگه.'),
    (18.48, 19.53, 'چطور کار می‌کنه؟'),
    (19.95, 23.10, 'لینکی که برات می‌فرستم رو کپی کن و داخل کلاد کد پیست کن.'),
    (23.49, 25.68, 'یه سبک انتخاب می‌کنی و داستانت رو می‌گی،'),
    (26.22, 28.20, 'کلاد خودش کارشو برات انجام میده.'),
    (28.95, 31.23, 'این فیلمی که می‌بینید هم با همین روش ساخته شده.'),
    (32.19, 35.25, 'برای دریافت لینک، کلمه‌ی «ریپو» رو کامنت کن.'),
]
cues = [{'t0': r(M(a) - .05), 't1': r(M(b) + .35), 'text': t} for a, b, t in SUBS]
for i, c in enumerate(cues):                             # hold ≥ max(1.8 s, speech + 0.6 s), never into the next cue
    c['t1'] = max(c['t1'], r(c['t0'] + 1.8))
    if i + 1 < len(cues): c['t1'] = min(c['t1'], r(cues[i + 1]['t0'] - .04))
cues[-1]['t1'] = END
os.makedirs(os.path.join(FILM, 'out'), exist_ok=True)
json.dump(cues, open(os.path.join(FILM, 'out', 'cues.json'), 'w'), ensure_ascii=False, indent=1)
print('pieces', [(a, b, round(f, 2), round(f + b - a, 2)) for a, b, f in pl])
print(json.dumps(A, ensure_ascii=False))
for c in cues: print(f"{c['t0']:6.2f} {c['t1']:6.2f} {c['t1'] - c['t0']:.2f}  {c['text']}")
